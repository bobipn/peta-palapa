#!/usr/bin/env node
/**
 * Generates supabase/seed.sql from the bundled, provenance-carrying dataset
 * (src/lib/data/schools.seed.json + references.json). Run after scripts/build-seed.mjs.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const db = JSON.parse(fs.readFileSync(path.join(ROOT, "src/lib/data/schools.seed.json"), "utf8"));
const refs = JSON.parse(fs.readFileSync(path.join(ROOT, "src/lib/data/references.json"), "utf8"));

const q = (v) => {
  if (v === undefined || v === null || (typeof v === "number" && !Number.isFinite(v))) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(q).join(",")}]::text[]` : "'{}'::text[]";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const date = (v) => (v && /^\d{4}-\d{2}-\d{2}$/.test(v) ? q(v) : "null");
const out = [];
out.push("-- Generated by scripts/generate-seed-sql.mjs — do not edit by hand.");
out.push(`-- Dataset generated ${db.generatedAt}; ${db.schools.length} institutions, ${db.fees.length} fee schedules, ${db.history.length} history points.`);
out.push("begin;");

const insert = (table, cols, rows) => {
  if (!rows.length) return;
  for (let i = 0; i < rows.length; i += 200) {
    const chunk = rows.slice(i, i + 200);
    out.push(`insert into public.${table} (${cols.join(", ")}) values\n${chunk.map((r) => `  (${r.join(", ")})`).join(",\n")}\non conflict do nothing;`);
  }
};

insert(
  "schools",
  ["id", "name", "foundation", "ownership", "is_university", "categories", "curricula", "province", "city", "district", "address", "latitude", "longitude", "website", "origin", "archived", "notes"],
  db.schools.map((s) => [
    q(s.id), q(s.name), q(s.foundation), q(s.ownership), q(!!s.isUniversity), q(s.categories), q(s.curricula),
    q(s.location.province), q(s.location.city), q(s.location.district), q(s.location.address), q(s.location.lat), q(s.location.lng),
    q(s.website), q("seed"), q(!!s.archived), q(s.notes),
  ]),
);
insert(
  "school_levels",
  ["school_id", "level"],
  db.schools.flatMap((s) => s.levels.map((l) => [q(s.id), `${q(l)}::public.education_level`])),
);
insert(
  "universities",
  ["school_id", "short_name", "university_type"],
  db.schools.filter((s) => s.isUniversity).map((s) => [q(s.id), q(s.id.replace(/^univ-/, "").toUpperCase()), q(s.ownership === "negeri" ? "PTN / kedinasan" : "PTS")]),
);
const locs = new Map();
for (const s of db.schools) locs.set(`${s.location.province}|${s.location.city}|${s.location.district ?? ""}`, s.location);
insert("locations", ["province", "city", "district"], [...locs.values()].map((l) => [q(l.province), q(l.city), q(l.district)]));
const curr = [...new Set(db.schools.flatMap((s) => s.curricula))];
insert("curriculums", ["id", "name"], curr.map((c, i) => [q(`cur-${i + 1}`), q(c)]));

insert(
  "school_fees",
  [
    "id", "school_id", "level", "program", "academic_year", "months_billed", "is_primary", "incomplete", "archived", "notes",
    "source", "source_url", "source_type", "data_date", "accessed_date", "last_verified", "verification_status", "data_confidence",
    "evidence", "provenance_notes", "academic_year_inferred",
  ],
  db.fees.map((f) => {
    const p = f.provenance;
    return [
      q(f.id), q(f.schoolId), `${q(f.level)}::public.education_level`, q(f.program), q(f.academicYear), q(f.monthsBilled ?? 12), q(!!f.primary), q(!!f.incomplete), q(!!f.archived), q(f.notes),
      q(p.source || "Sumber riset"), q(p.sourceUrl), q(p.sourceType), date(p.dataDate), date(p.accessedDate), date(p.lastVerified), `${q(p.verificationStatus)}::public.verification_status`, `${q(p.confidence)}::public.data_confidence`,
      q(p.evidence), q(p.notes), q(!!p.academicYearInferred),
    ];
  }),
);
insert(
  "school_fee_components",
  ["id", "fee_id", "sort_order", "code", "label", "cost_group", "category", "frequency", "amount", "amount_min", "amount_max", "inflation", "included", "excluded", "excluded_reason", "estimated", "frequency_inferred", "from_grade", "to_grade", "tier_group", "tier_label", "tier_default", "verbatim", "note"],
  db.fees.flatMap((f) =>
    f.components.map((c, i) => [
      q(c.id), q(f.id), q(i), q(c.code), q(c.label), `${q(c.group)}::public.cost_group`, q(c.category), `${q(c.frequency)}::public.fee_frequency`, q(Math.round(c.amount)), q(c.amountMin), q(c.amountMax), q(c.inflation),
      q(c.included ?? null), q(!!c.excluded), q(c.excludedReason), q(!!c.estimated), q(!!c.frequencyInferred), q(c.fromGrade), q(c.toGrade), q(c.tierGroup), q(c.tierLabel), q(c.tierDefault ?? null), q(c.verbatim), q(c.note),
    ]),
  ),
);
insert(
  "school_fee_history",
  ["id", "school_id", "level", "program", "component_code", "frequency", "academic_year", "amount", "source", "source_url", "source_type", "data_date", "accessed_date", "verification_status", "data_confidence", "notes"],
  db.history.map((h) => [
    q(h.id), q(h.schoolId), `${q(h.level)}::public.education_level`, q(h.program), q(h.componentCode), `${q(h.frequency)}::public.fee_frequency`, q(h.academicYear), q(Math.round(h.amount)),
    q(h.provenance.source || "Sumber riset"), q(h.provenance.sourceUrl), q(h.provenance.sourceType), date(h.provenance.dataDate), date(h.provenance.accessedDate), `${q(h.provenance.verificationStatus)}::public.verification_status`, `${q(h.provenance.confidence)}::public.data_confidence`, q(h.provenance.notes),
  ]),
);
insert(
  "inflation_rates",
  ["series", "period", "value_pct", "base_year", "source", "source_url", "source_type", "accessed_date", "evidence", "verbatim"],
  refs.inflationSeries.map((r) => [q(r.series), q(r.period), q(r.valuePct), q(r.baseYear), q(r.source.publisher ?? r.source.title), q(r.source.url), q(r.source.sourceType), date(r.source.accessedDate), q(r.source.evidence), q(r.verbatim)]),
);
out.push("commit;");
fs.writeFileSync(path.join(ROOT, "supabase/seed.sql"), out.join("\n") + "\n");
console.log(`seed.sql written (${(out.join("\n").length / 1024).toFixed(0)} KB)`);
